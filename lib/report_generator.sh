EOF
    sed -i "s/DATE_PLACEHOLDER/$(date '+%Y-%m-%d %H:%M:%S')/g" "$output_file"
    sed -i "s/TOTAL_CAPTURES_PLACEHOLDER/${total_captures}/g" "$output_file"
    sed -i "s/UNIQUE_IPS_PLACEHOLDER/${unique_ips}/g" "$output_file"
    sed -i "s/SUCCESS_RATE_PLACEHOLDER/$(calculate_success_rate)/g" "$output_file"

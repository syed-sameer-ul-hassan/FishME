    </style>
</head>
<body>
    <div class="container">
        <div class="header">
            <h1>FishMe Phishing Report</h1>
            <p>Generated: DATE_PLACEHOLDER</p>
        </div>
        
        <div class="stats-grid">
            <div class="stat-card">
                <h3>Total Captures</h3>
                <div class="value">TOTAL_CAPTURES_PLACEHOLDER</div>
            </div>
            <div class="stat-card">
                <h3>Unique IPs</h3>
                <div class="value">UNIQUE_IPS_PLACEHOLDER</div>
            </div>
            <div class="stat-card">
                <h3>Success Rate</h3>
                <div class="value">SUCCESS_RATE_PLACEHOLDER%</div>
            </div>
            <div class="stat-card">
                <h3>Active Sessions</h3>
                <div class="value">ACTIVE_SESSIONS_PLACEHOLDER</div>

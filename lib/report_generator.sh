#!/bin/bash

REPORTS_DIR="${BASE_DIR}/reports"
CAPTURE_DIR="${BASE_DIR}/capture"
SESSIONS_DIR="${BASE_DIR}/sessions"

init_report_generator() {
    mkdir -p "$REPORTS_DIR"
}

generate_html_report() {
    local output_file="${1:-${REPORTS_DIR}/report_$(date +%Y%m%d_%H%M%S).html}"
    local session_filter="${2:-}"
    
    echo "Generating HTML report: $output_file"
    local total_captures
    total_captures=$(find "$CAPTURE_DIR" -name "*.json" 2>/dev/null | wc -l)
    
    local unique_ips
    declare -A ip_set
    for capture_file in "${CAPTURE_DIR}"/*.json; do
        if [[ -f "$capture_file" ]]; then
            local ip
            ip=$(jq -r '.ip // "N/A"' "$capture_file" 2>/dev/null)
            if [[ -n "$ip" && "$ip" != "N/A" ]]; then
                ip_set["$ip"]=1
            fi
        fi
    done
    unique_ips=${#ip_set[@]}
    cat > "$output_file" << 'EOF'
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>FishMe Phishing Report</title>
    <style>
        * { margin: 0; padding: 0; box-sizing: border-box; }
        body { font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; background: #f5f5f5; color: #333; }

                    <tr>
                        <th>Timestamp</th>
                        <th>Template</th>
                        <th>Username</th>
                        <th>IP Address</th>
                        <th>Status</th>
                    </tr>
                </thead>
                <tbody>
CAPTURE_TABLE_PLACEHOLDER
                </tbody>
            </table>
        </div>
        
        <div class="section">
            <h2>Template Performance</h2>
            <table>
                <thead>
                    <tr>
                        <th>Template</th>
                        <th>Captures</th>
                        <th>Success Rate</th>
                    </tr>
                </thead>
                <tbody>
TEMPLATE_TABLE_PLACEHOLDER
                </tbody>
            </table>
        </div>
        
        <div class="footer">
            <p>Generated by FishMe v1.0.0 - Phishing Tool</p>
        </div>
    </div>
</body>

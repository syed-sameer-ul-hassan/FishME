                        <td><span class=\"badge badge-success\">${template}</span></td>
                        <td>${username}</td>
                        <td>${ip}</td>
                        <td><span class=\"badge badge-success\">Captured</span></td>
                    </tr>"
            ((count++))
        fi
    done
    
    if [[ -z "$capture_table" ]]; then
        capture_table="<tr><td colspan=\"5\" style=\"text-align:center;\">No captures found</td></tr>"
    fi
    
    sed -i "s|CAPTURE_TABLE_PLACEHOLDER|${capture_table}|g" "$output_file"
    local template_table=""
    declare -A template_counts
    for capture_file in "${CAPTURE_DIR}"/*.json; do
        if [[ -f "$capture_file" ]]; then
            local template
            template=$(basename "$capture_file" .json)
            template_counts[$template]=$((${template_counts[$template]:-0} + 1))
        fi
    done
    
    for template in "${!template_counts[@]}"; do
        local count=${template_counts[$template]}
        local rate=100
        template_table="${template_table}
                    <tr>
                        <td><span class=\"badge badge-warning\">${template}</span></td>
                        <td>${count}</td>
                        <td>${rate}%</td>
                    </tr>"
    done
    
    if [[ -z "$template_table" ]]; then
        template_table="<tr><td colspan=\"3\" style=\"text-align:center;\">No template data</td></tr>"
    fi
    
    sed -i "s|TEMPLATE_TABLE_PLACEHOLDER|${template_table}|g" "$output_file"
    echo "HTML report generated: $output_file"
}

generate_pdf_report() {
    local output_file="${1:-${REPORTS_DIR}/report_$(date +%Y%m%d_%H%M%S).pdf}"
    
    if ! command -v wkhtmltopdf &>/dev/null; then
        echo "wkhtmltopdf not found. Install it to generate PDF reports."
        echo "Ubuntu/Debian: sudo apt-get install wkhtmltopdf"
        return 1
    fi
    
    local html_file="${output_file%.pdf}.html"
    generate_html_report "$html_file"
    
    wkhtmltopdf "$html_file" "$output_file" 2>/dev/null
    rm -f "$html_file"
    
    echo "PDF report generated: $output_file"
}

generate_markdown_report() {
    local output_file="${1:-${REPORTS_DIR}/report_$(date +%Y%m%d_%H%M%S).md}"
    
    echo "Generating Markdown report: $output_file"
    cat > "$output_file" << EOF
# FishMe Phishing Report

**Generated:** $(date '+%Y-%m-%d %H:%M:%S')
**Version:** 1.0.0

---

## Executive Summary

This report provides a comprehensive overview of phishing activities conducted using FishMe.

### Key Metrics

- **Total Captures:** $(find "$CAPTURE_DIR" -name "*.json" 2>/dev/null | wc -l)
- **Unique IPs:** $(get_unique_ip_count)
- **Success Rate:** $(calculate_success_rate)%
- **Active Sessions:** $(get_active_session_count)

---

## Recent Captures

| Timestamp | Template | Username | IP Address | Status |
|-----------|----------|----------|------------|--------|
EOF
    local count=0
    for capture_file in "${CAPTURE_DIR}"/*.json; do
        if [[ -f "$capture_file" && $count -lt 20 ]]; then
            local template
            template=$(basename "$capture_file" .json)
            local timestamp
            timestamp=$(jq -r '.timestamp // "N/A"' "$capture_file" 2>/dev/null)
            local username
            username=$(jq -r '.username // "N/A"' "$capture_file" 2>/dev/null)
            local ip
            ip=$(jq -r '.ip // "N/A"' "$capture_file" 2>/dev/null)
            
            echo "| ${timestamp} | ${template} | ${username} | ${ip} | Captured |" >> "$output_file"
            ((count++))
        fi
    done
    cat >> "$output_file" << EOF

---

## Template Performance

| Template | Captures | Success Rate |
|----------|----------|-------------|
EOF
    declare -A template_counts
    for capture_file in "${CAPTURE_DIR}"/*.json; do
        if [[ -f "$capture_file" ]]; then
            local template
            template=$(basename "$capture_file" .json)
            template_counts[$template]=$((${template_counts[$template]:-0} + 1))
        fi
    done
    
    for template in "${!template_counts[@]}"; do
        local count=${template_counts[$template]}
        echo "| ${template} | ${count} | 100% |" >> "$output_file"
    done
    cat >> "$output_file" << EOF

---

## Recommendations

1. **Review High-Performing Templates:** Focus on templates with higher capture rates for future s.
2. **Analyze IP Patterns:** Review geographic distribution to identify target demographics.
3. **Security:** Use captured data to improve security programs.

---

*This report was generated automatically by FishMe.*
EOF
    echo "Markdown report generated: $output_file"
}

generate_json_report() {
    local output_file="${1:-${REPORTS_DIR}/report_$(date +%Y%m%d_%H%M%S).json}"
    
    echo "Generating JSON report: $output_file"
    
    local total_captures
    total_captures=$(find "$CAPTURE_DIR" -name "*.json" 2>/dev/null | wc -l)
    
    local unique_ips
    unique_ips=$(get_unique_ip_count)
    
    jq -n \
        --arg generated "$(date -Iseconds)" \
        --arg version "1.0.0" \
        --argjson total_captures "$total_captures" \
        --argjson unique_ips "$unique_ips" \
        --arg success_rate "$(calculate_success_rate)" \
        --argjson active_sessions "$(get_active_session_count)" \
        '{
            metadata: {
                generated: $generated,
                version: $version,
                tool: "FishMe"
            },
            summary: {
                total_captures: $total_captures,
                unique_ips: $unique_ips,
                success_rate: $success_rate,
                active_sessions: $active_sessions
            },
            captures: []
        }' > "$output_file"
    
    echo "JSON report generated: $output_file"
}

calculate_success_rate() {
    local total_captures
    total_captures=$(find "$CAPTURE_DIR" -name "*.json" 2>/dev/null | wc -l)
    local total_visits=1000  # Placeholder - would need actual visit tracking
    
    if [[ $total_visits -gt 0 ]]; then
        echo "scale=2; ($total_captures * 100) / $total_visits" | bc
    else
        echo "0"
    fi
}

get_unique_ip_count() {
    declare -A ip_set
    for capture_file in "${CAPTURE_DIR}"/*.json; do
        if [[ -f "$capture_file" ]]; then
            local ip
            ip=$(jq -r '.ip // "N/A"' "$capture_file" 2>/dev/null)
            if [[ -n "$ip" && "$ip" != "N/A" ]]; then
                ip_set["$ip"]=1
            fi
        fi
    done
    echo "${#ip_set[@]}"
}

get_active_session_count() {
    local count=0
    for session_file in "${SESSIONS_DIR}"/*.json; do
        if [[ -f "$session_file" ]]; then
            local status
            status=$(jq -r '.status' "$session_file" 2>/dev/null)
            if [[ "$status" == "active" ]]; then
                ((count++))
            fi
        fi
    done
    echo "$count"
}

list_reports() {
    echo "Available Reports:"
    echo "=================="
    
    if [[ ! -d "$REPORTS_DIR" ]] || [[ -z "$(ls -A "$REPORTS_DIR")" ]]; then
        echo "No reports found."
        return
    fi
    
    local i=1
    for report_file in "${REPORTS_DIR}"/*; do
        if [[ -f "$report_file" ]]; then
            local filename
            filename=$(basename "$report_file")
            local filesize
            filesize=$(du -h "$report_file" | cut -f1)
            local filedate
            filedate=$(stat -c %y "$report_file" 2>/dev/null | cut -d'.' -f1)
            
            printf "  ${GREEN}[%d]${RESET} ${BOLD}%s${RESET} (%s) - %s\n" "$i" "$filename" "$filesize" "$filedate"
            ((i++))
        fi
    done
}

delete_report() {
    local report_name="$1"
    local report_file="${REPORTS_DIR}/${report_name}"
    
    if [[ ! -f "$report_file" ]]; then
        echo "Report not found: $report_name"
        return 1
    fi
    
    rm "$report_file"
    echo "Deleted report: $report_name"
}

generate_all_reports() {
    local base_name="${1:-report_$(date +%Y%m%d_%H%M%S)}"
    
    echo "Generating all report formats..."
    
    generate_html_report "${REPORTS_DIR}/${base_name}.html"
    generate_markdown_report "${REPORTS_DIR}/${base_name}.md"
    generate_json_report "${REPORTS_DIR}/${base_name}.json"
    
    if command -v wkhtmltopdf &>/dev/null; then
        generate_pdf_report "${REPORTS_DIR}/${base_name}.pdf"
    else
        echo "Skipping PDF report (wkhtmltopdf not installed)"
    fi
    
    echo "All reports generated."
}
